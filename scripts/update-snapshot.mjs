// Saves an offline copy of the Google Sheet: data/locations.js plus every
// location image in assets/locations/. The map loads this snapshot instantly
// (and when offline / opened from disk), then swaps in the live sheet.
//
// Usage: node scripts/update-snapshot.mjs

import { mkdir, writeFile, readdir, unlink } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const SheetParser = require('../js/sheet-parser.js');

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const IMG_DIR = join(ROOT, 'assets', 'locations');
const EXT = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp', 'image/gif': 'gif' };

const html = await (await fetch(SheetParser.URLS.html)).text();
const entries = SheetParser.fromHtml(html);
console.log(`Parsed ${entries.length} entries`);

await mkdir(IMG_DIR, { recursive: true });
const keep = new Set();
let failed = 0;

// Downloads each image and returns copies pointing at the local files
// (keeping any extra fields such as width/height).
async function saveImages(entry, images, prefix) {
  const local = [];
  for (const [i, img] of images.entries()) {
    // 1600px-wide JPEG keeps the whole snapshot small
    const url = img.full.replace(/=w1920-rj-l88$/, '=w1600-rj-l82');
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const ext = EXT[res.headers.get('content-type')?.split(';')[0]] || 'jpg';
      const name = `${entry.id}-${prefix}${i + 1}.${ext}`;
      await writeFile(join(IMG_DIR, name), Buffer.from(await res.arrayBuffer()));
      keep.add(name);
      local.push({ ...img, thumb: `assets/locations/${name}`, full: `assets/locations/${name}` });
    } catch (err) {
      failed++;
      console.warn(`  ${entry.id} ${prefix || ''}image ${i + 1}: ${err.message}`);
      local.push(img);
    }
  }
  return local;
}

for (const entry of entries) {
  entry.images = await saveImages(entry, entry.images, '');
  entry.noteImages = await saveImages(entry, entry.noteImages || [], 'note-');
  process.stdout.write('.');
}

// Remove images for rows that no longer exist
for (const name of await readdir(IMG_DIR)) if (!keep.has(name)) await unlink(join(IMG_DIR, name));

await mkdir(join(ROOT, 'data'), { recursive: true });
const snapshot = { savedAt: new Date().toISOString(), entries };
await writeFile(
  join(ROOT, 'data', 'locations.js'),
  `// Offline snapshot of the Google Sheet (generated by scripts/update-snapshot.mjs)\nwindow.SNAPSHOT = ${JSON.stringify(snapshot, null, 1)};\n`
);
console.log(`\nSaved ${entries.length} entries and ${keep.size} images (${failed} image downloads failed)`);
